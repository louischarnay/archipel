import type { Column, ColumnType, Table } from './schema.js';

const DATE = { type: 'string', format: 'date-time' };
const SCALARS: Partial<Record<ColumnType, { type: string; format?: string }>> = {
  integer: { type: 'integer' },
  number: { type: 'number' },
  boolean: { type: 'boolean' },
  date: DATE,
  datetime: DATE,
};

export const columnsOf = (table: Table): [string, Column][] => Object.entries(table.columns);

export function primaryKey(table: Table): string {
  const pk = columnsOf(table).find(([, column]) => column.pk);
  if (!pk) throw new Error('Table without a pk column');
  return pk[0];
}

// An integer pk is chosen at creation; the others are generated by the platform.
export const insertRequires = (column: Column): boolean =>
  column.pk ? column.type === 'integer' : Boolean(column.required) && column.default === undefined;

function columnSchema(column: Column): object {
  if (column.type === 'json') return column.required ? { not: { type: 'null' } } : {};
  const values = column.values ?? [];
  if (column.type === 'enum') return { enum: column.required ? values : [...values, null] };
  const scalar = SCALARS[column.type] ?? { type: 'string' };
  return column.required ? scalar : { ...scalar, type: [scalar.type, 'null'] };
}

// One definition of a table's rows: CRUD validation, the app's OpenAPI and generated types all derive from it.
export function rowSchema(table: Table, { partial = false }: { partial?: boolean } = {}) {
  const columns = columnsOf(table);
  return {
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(columns.map(([name, column]) => [name, columnSchema(column)])),
    required: partial ? [] : columns.filter(([, column]) => !column.pk && insertRequires(column)).map(([name]) => name),
  };
}
